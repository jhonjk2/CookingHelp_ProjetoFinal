    <h1>Política de Privacidade</h1>

    <h2>Que dados Recolhemos</h2>
    <p>Quando crias uma conta no Cooking Help, guardamos o teu <strong>nome</strong>, o teu <strong>email</strong>, o <strong>hash da tua password</strong>(nunca a password em si) e a <strong>data em que aceitaste esta política</strong>.</p>

    <h2>Para que servem</h2>
    <p>O email e a password servem para iniciares sessão. O nome serve parate identificar na aplicação. A data do Consentimento serve para provar que o deste. Não recolhemos mais nenhum dado pessoal (princípio da minimização).</p>

    <h2>Base lgal e prazo</h2>
    <p>O tratamento baseia-se no teu consentimeto. Os dados são guardados enquanto a conta existir e apagados quando a apagares.</p>

    <h2>Os teus direitos</h2>
    <p>Podes consultar os teus dados e apagar a tua conta a qualquer momento, na página <em>A minha conta</em>. Para outros pedidos, contactar o responsável pelo Cooking Help.</p>
